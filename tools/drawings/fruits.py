def uvas(d):
    d.band("tallo", [(512, 300), (522, 185)], 34)
    d.leaf("hoja", (500, 230), (320, 170), 48)
    rows = [
        (696, [512]),
        (584, [447, 577]),
        (472, [382, 512, 642]),
        (360, [317, 447, 577, 707]),
    ]
    n = 0
    for y, xs in rows:
        for x in xs:
            n += 1
            d.circle(f"uva_{n}", x, y, 74)
    d.eyes(512, 462, 28, 13)
    d.smile(512, 494, 24, 10, 8)
